export const supportedLocales = ["zh-TW", "en", "es", "ja", "fr", "pt"] as const;
export type Locale = (typeof supportedLocales)[number];

export const localeLabels: Record<Locale, string> = {
  "zh-TW": "繁體中文",
  en: "English",
  es: "Español",
  ja: "日本語",
  fr: "Français",
  pt: "Português",
};

export function normalizeLocale(value?: string | null): Locale {
  const locale = String(value || "").toLowerCase();
  if (locale.startsWith("zh")) return "zh-TW";
  if (locale.startsWith("es")) return "es";
  if (locale.startsWith("ja")) return "ja";
  if (locale.startsWith("fr")) return "fr";
  if (locale.startsWith("pt")) return "pt";
  if (locale.startsWith("en")) return "en";
  return "zh-TW";
}

export type TranslationKey = keyof (typeof messages)["zh-TW"];

export function translate(locale: Locale, key: TranslationKey, variables: Record<string, string | number> = {}) {
  const dict = messages[locale] as Record<string, string> || messages["zh-TW"];
  const template = dict[key] || (messages.en as Record<string, string>)[key] || messages["zh-TW"][key] || key;
  return template.replace(/\{(\w+)\}/g, (match, name) => Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match);
}

