  let activeLocale = DEFAULT_LOCALE;

  function normalizeLocale(locale) {
    const value = String(locale || "").toLowerCase();
    if (value === "zh-tw" || value === "zh-hant" || value.startsWith("zh-hant-")) return "zh-TW";
    if (value.startsWith("zh")) return "zh-TW";
    return "en";
  }

  function interpolate(message, variables) {
    return String(message).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) =>
      Object.prototype.hasOwnProperty.call(variables || {}, key) ? String(variables[key]) : match
    );
  }

  function t(key, variables = {}) {
    const message = dictionaries[activeLocale]?.[key] ?? dictionaries[DEFAULT_LOCALE]?.[key] ?? key;
    return interpolate(message, variables);
  }

  function localizeDocument(root = document) {
    if (!root?.querySelectorAll) return;
    root.documentElement?.setAttribute("lang", activeLocale);
    root.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = t(element.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
    });
    root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
    });
    root.querySelectorAll("[data-i18n-title]").forEach((element) => {
      element.setAttribute("title", t(element.dataset.i18nTitle));
    });
  }

  async function init(root = document) {
    let storedLocale = "";
    try {
      storedLocale = (await chrome.storage.local.get(STORAGE_KEY))[STORAGE_KEY] || "";
    } catch (_) {}
    const browserLocale = global.chrome?.i18n?.getUILanguage?.() || global.navigator?.language;
    activeLocale = normalizeLocale(storedLocale || browserLocale || DEFAULT_LOCALE);
    localizeDocument(root);
    return activeLocale;
  }

  async function setLocale(locale, root = document) {
    activeLocale = normalizeLocale(locale);
    try { await chrome.storage.local.set({ [STORAGE_KEY]: activeLocale }); } catch (_) {}
    localizeDocument(root);
    global.dispatchEvent?.(new CustomEvent("chamber:locale-changed", { detail: { locale: activeLocale } }));
    return activeLocale;
  }

  function formatDate(value, options) {
    return new Intl.DateTimeFormat(activeLocale, options).format(value instanceof Date ? value : new Date(value));
  }

  function formatNumber(value, options) {
    return new Intl.NumberFormat(activeLocale, options).format(value);
  }

  global.ChamberI18n = Object.freeze({
    dictionaries,
    supportedLocales: Object.freeze(["zh-TW", "en"]),
    defaultLocale: DEFAULT_LOCALE,
    normalizeLocale,
    init,
    setLocale,
    getLocale: () => activeLocale,
    t,
    localizeDocument,
    formatDate,
    formatNumber
  });
